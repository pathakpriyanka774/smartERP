-- Employee Attendance module.
-- PostgreSQL port of attendance-schema.sql.
--
-- One row per employee per day, enforced by a unique constraint rather than by
-- application logic, so a double check-in cannot create a duplicate day.

DROP TABLE IF EXISTS EmployeeAttendance CASCADE;

CREATE TABLE EmployeeAttendance (
    AttendanceID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeID     INT NOT NULL REFERENCES Employees(EmployeeID),
    AttendanceDate DATE NOT NULL,
    CheckInTime    TIMESTAMP,
    CheckOutTime   TIMESTAMP,
    Status         VARCHAR(20) NOT NULL DEFAULT 'present',
    TotalHours     DECIMAL(5,2) DEFAULT 0,
    Notes          VARCHAR(500),
    CreatedAt      TIMESTAMP DEFAULT LOCALTIMESTAMP,
    UpdatedAt      TIMESTAMP DEFAULT LOCALTIMESTAMP,

    -- One attendance record per employee per day.
    CONSTRAINT UQ_Attendance_Employee_Date UNIQUE (EmployeeID, AttendanceDate),
    CONSTRAINT CK_Attendance_Status CHECK (Status IN ('present','absent','half-day','leave','late')),
    -- A checkout before the corresponding check-in is always a data error.
    CONSTRAINT CK_Attendance_Times CHECK (CheckOutTime IS NULL OR CheckInTime IS NULL OR CheckOutTime >= CheckInTime)
);

CREATE INDEX IX_Attendance_Date ON EmployeeAttendance (AttendanceDate);

-- Whole minutes between two times, counted the way SQL Server's
-- DATEDIFF(minute, a, b) counts them: minute boundaries crossed, not elapsed
-- time rounded down. Worked hours were always computed that way, so this keeps
-- TotalHours identical to the values recorded before the move to PostgreSQL.
CREATE OR REPLACE FUNCTION minutes_between(a TIMESTAMP, b TIMESTAMP)
RETURNS INT
LANGUAGE sql IMMUTABLE AS $$
    SELECT (EXTRACT(EPOCH FROM date_trunc('minute', b) - date_trunc('minute', a)) / 60)::INT
$$;

-- Attendance joined to the employee, for listing screens.
CREATE VIEW vw_AttendanceDetail AS
SELECT
    a.AttendanceID,
    a.EmployeeID,
    e.EmployeeCode,
    e.Name AS EmployeeName,
    e.Department,
    e.Position,
    a.AttendanceDate,
    a.CheckInTime,
    a.CheckOutTime,
    a.Status,
    a.TotalHours,
    a.Notes
FROM EmployeeAttendance a
JOIN Employees e ON a.EmployeeID = e.EmployeeID;

-- Per-day counts, used by the dashboard tiles.
CREATE VIEW vw_AttendanceDailySummary AS
SELECT
    a.AttendanceDate,
    COUNT(*)                                                     AS TotalRecords,
    SUM(CASE WHEN a.Status = 'present'  THEN 1 ELSE 0 END)       AS PresentCount,
    SUM(CASE WHEN a.Status = 'absent'   THEN 1 ELSE 0 END)       AS AbsentCount,
    SUM(CASE WHEN a.Status = 'half-day' THEN 1 ELSE 0 END)       AS HalfDayCount,
    SUM(CASE WHEN a.Status = 'leave'    THEN 1 ELSE 0 END)       AS LeaveCount,
    SUM(CASE WHEN a.Status = 'late'     THEN 1 ELSE 0 END)       AS LateCount,
    CAST(COALESCE(SUM(a.TotalHours), 0) AS DECIMAL(10,2))        AS TotalHours
FROM EmployeeAttendance a
GROUP BY a.AttendanceDate;

CREATE OR REPLACE FUNCTION sp_AttendanceCheckIn(
    p_EmployeeID     INT,
    p_AttendanceDate DATE      DEFAULT NULL,
    p_CheckInTime    TIMESTAMP DEFAULT NULL,
    p_Notes          VARCHAR   DEFAULT NULL,
    -- Cutoff for a late arrival. Supplied by the service from
    -- ATTENDANCE_LATE_AFTER; the default here keeps direct SQL calls consistent.
    p_LateAfter      VARCHAR   DEFAULT '10:30'
)
RETURNS TABLE (Result TEXT, Message TEXT, AttendanceID INT, Status TEXT, CheckInTime TEXT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Date       DATE      := COALESCE(p_AttendanceDate, CURRENT_DATE);
    v_In         TIMESTAMP := COALESCE(p_CheckInTime, LOCALTIMESTAMP);
    v_ID         INT;
    v_ExistingIn TIMESTAMP;
    v_Status     VARCHAR(20);
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Employees e WHERE e.EmployeeID = p_EmployeeID AND e.IsActive = TRUE) THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Employee not found or inactive'::TEXT, NULL::INT, NULL::TEXT, NULL::TEXT;
        RETURN;
    END IF;

    SELECT a.AttendanceID, a.CheckInTime INTO v_ID, v_ExistingIn
    FROM EmployeeAttendance a
    WHERE a.EmployeeID = p_EmployeeID AND a.AttendanceDate = v_Date;

    -- Only an actual recorded arrival blocks a second check-in. A row that
    -- exists because the day was marked absent or on leave has no CheckInTime,
    -- and checking in should correct it rather than be refused.
    IF v_ID IS NOT NULL AND v_ExistingIn IS NOT NULL THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Already checked in for this date'::TEXT, NULL::INT, NULL::TEXT, NULL::TEXT;
        RETURN;
    END IF;

    v_Status := CASE WHEN v_In::TIME > p_LateAfter::TIME THEN 'late' ELSE 'present' END;

    IF v_ID IS NULL THEN
        INSERT INTO EmployeeAttendance (EmployeeID, AttendanceDate, CheckInTime, Status, Notes)
        VALUES (p_EmployeeID, v_Date, v_In, v_Status, p_Notes)
        RETURNING EmployeeAttendance.AttendanceID INTO v_ID;
    ELSE
        UPDATE EmployeeAttendance
        SET CheckInTime = v_In,
            Status      = v_Status,
            Notes       = COALESCE(p_Notes, Notes),
            UpdatedAt   = LOCALTIMESTAMP
        WHERE EmployeeAttendance.AttendanceID = v_ID;
    END IF;

    RETURN QUERY SELECT 'Success'::TEXT, 'Checked in'::TEXT, v_ID, v_Status::TEXT, to_char(v_In, 'HH24:MI');
END;
$$;

CREATE OR REPLACE FUNCTION sp_AttendanceCheckOut(
    p_EmployeeID     INT,
    p_AttendanceDate DATE      DEFAULT NULL,
    p_CheckOutTime   TIMESTAMP DEFAULT NULL
)
RETURNS TABLE (Result TEXT, Message TEXT, AttendanceID INT, TotalHours DECIMAL, CheckOutTime TEXT, Status TEXT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Date        DATE      := COALESCE(p_AttendanceDate, CURRENT_DATE);
    v_Out         TIMESTAMP := COALESCE(p_CheckOutTime, LOCALTIMESTAMP);
    v_ID          INT;
    v_In          TIMESTAMP;
    v_ExistingOut TIMESTAMP;
    v_Hours       DECIMAL(5,2);
    v_Status      VARCHAR(20);
BEGIN
    SELECT a.AttendanceID, a.CheckInTime, a.CheckOutTime, a.Status
      INTO v_ID, v_In, v_ExistingOut, v_Status
    FROM EmployeeAttendance a
    WHERE a.EmployeeID = p_EmployeeID AND a.AttendanceDate = v_Date;

    IF v_ID IS NULL OR v_In IS NULL THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'No check-in found for this date'::TEXT, NULL::INT, NULL::DECIMAL, NULL::TEXT, NULL::TEXT;
        RETURN;
    END IF;
    IF v_ExistingOut IS NOT NULL THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Already checked out for this date'::TEXT, NULL::INT, NULL::DECIMAL, NULL::TEXT, NULL::TEXT;
        RETURN;
    END IF;
    IF v_Out < v_In THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Check-out cannot precede check-in'::TEXT, NULL::INT, NULL::DECIMAL, NULL::TEXT, NULL::TEXT;
        RETURN;
    END IF;

    v_Hours := CAST(minutes_between(v_In, v_Out) / 60.0 AS DECIMAL(5,2));

    -- Status is left as check-in set it: a late arrival stays 'late' for the
    -- day, and overwriting it here would silently erase that.
    UPDATE EmployeeAttendance
    SET CheckOutTime = v_Out,
        TotalHours   = v_Hours,
        UpdatedAt    = LOCALTIMESTAMP
    WHERE EmployeeAttendance.AttendanceID = v_ID;

    RETURN QUERY SELECT 'Success'::TEXT, 'Checked out'::TEXT, v_ID, v_Hours::DECIMAL,
                        to_char(v_Out, 'HH24:MI'), v_Status::TEXT;
END;
$$;

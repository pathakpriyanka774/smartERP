-- Create Charts module: charts authored by hand in Application Settings.
--
-- Created only if absent, unlike the other files, so this module can be added
-- to a database that already holds data — apply it on its own with:
--   psql -h localhost -U <DB_USER> -d smarterp -f postgres/08-charts.sql
--
-- A chart's labels, series, values and colours are one JSON document, for the
-- same reason a page's layout is: the set of chart types and options will keep
-- growing, and a relational shape would need a migration for every one.
-- IS JSON keeps a malformed definition out; the service validates its shape.

CREATE TABLE IF NOT EXISTS SavedCharts (
    ChartID     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title       VARCHAR(150) NOT NULL,
    Description VARCHAR(500),
    ChartType   VARCHAR(20)  NOT NULL,
    Definition  TEXT         NOT NULL,   -- JSON: labels, series, colours, options
    CreatedBy   INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt   TIMESTAMP DEFAULT LOCALTIMESTAMP,
    UpdatedAt   TIMESTAMP DEFAULT LOCALTIMESTAMP,

    CONSTRAINT CK_SavedCharts_Type CHECK (ChartType IN ('bar','hbar','stacked','line','area','pie','donut')),
    CONSTRAINT CK_SavedCharts_Json CHECK (Definition IS JSON)
);

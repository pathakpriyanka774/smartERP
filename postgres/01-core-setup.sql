-- SmartERP core tables: users, employees, payroll.
-- PostgreSQL port of complete-setup-database.sql + fix-ctc-procedure.sql.
--
-- Identifiers are written in PascalCase but left unquoted, so PostgreSQL
-- stores them lower-case. shared/database.js restores the PascalCase names on
-- result rows, which keeps every service's JSON contract unchanged.

DROP TABLE IF EXISTS Payrolls CASCADE;
DROP TABLE IF EXISTS Employees CASCADE;
DROP TABLE IF EXISTS Users CASCADE;

CREATE TABLE Users (
    UserID       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username     VARCHAR(50)  UNIQUE NOT NULL,
    Email        VARCHAR(100) UNIQUE NOT NULL,
    PasswordHash VARCHAR(255) NOT NULL,
    Role         VARCHAR(20)  DEFAULT 'Employee',
    IsActive     BOOLEAN      DEFAULT TRUE,
    CreatedAt    TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE Employees (
    EmployeeID       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeCode     VARCHAR(20)  UNIQUE NOT NULL,
    Name             VARCHAR(100) NOT NULL,
    Email            VARCHAR(100) UNIQUE NOT NULL,
    Phone            VARCHAR(20),
    Position         VARCHAR(100) NOT NULL,
    Department       VARCHAR(100) NOT NULL,
    JoiningDate      DATE         DEFAULT CURRENT_DATE,
    BaseSalary       DECIMAL(12,2) NOT NULL,
    CTC              DECIMAL(15,2),
    Tasks            TEXT,
    Address          VARCHAR(500),
    EmergencyContact VARCHAR(200),
    Status           VARCHAR(20)  DEFAULT 'active',
    IsActive         BOOLEAN      DEFAULT TRUE,
    CreatedAt        TIMESTAMP    DEFAULT LOCALTIMESTAMP
);

CREATE TABLE Payrolls (
    PayrollID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeID  INT REFERENCES Employees(EmployeeID),
    Month       VARCHAR(7)    NOT NULL,
    BaseSalary  DECIMAL(12,2) NOT NULL,
    Allowances  DECIMAL(10,2) DEFAULT 0,
    Deductions  DECIMAL(10,2) DEFAULT 0,
    ProcessedBy INT,
    ProcessedAt TIMESTAMP     DEFAULT LOCALTIMESTAMP
);

-- Includes the fix from fix-ctc-procedure.sql: a supplied CTC is respected,
-- and only a missing or zero one is derived from the base salary.
CREATE OR REPLACE FUNCTION sp_CreateEmployee(
    p_Name             VARCHAR,
    p_Email            VARCHAR,
    p_Position         VARCHAR,
    p_Department       VARCHAR,
    p_BaseSalary       DECIMAL,
    p_Phone            VARCHAR DEFAULT NULL,
    p_JoiningDate      DATE    DEFAULT NULL,
    p_CTC              DECIMAL DEFAULT NULL,
    p_Tasks            TEXT    DEFAULT NULL,
    p_Address          VARCHAR DEFAULT NULL,
    p_EmergencyContact VARCHAR DEFAULT NULL
)
RETURNS TABLE (
    id INT, employeeCode VARCHAR, name VARCHAR, email VARCHAR, phone VARCHAR,
    "position" VARCHAR, department VARCHAR, joiningDate DATE, baseSalary DECIMAL,
    ctc DECIMAL, tasks TEXT, address VARCHAR, emergencyContact VARCHAR,
    status VARCHAR, isActive BOOLEAN
)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Next INT;
    v_ID   INT;
BEGIN
    SELECT COUNT(*) + 1 INTO v_Next FROM Employees;

    INSERT INTO Employees (
        EmployeeCode, Name, Email, Phone, Position, Department,
        JoiningDate, BaseSalary, CTC, Tasks, Address, EmergencyContact
    )
    VALUES (
        -- EMP001..EMP999, then widens instead of wrapping back to EMP000.
        'EMP' || LPAD(v_Next::TEXT, GREATEST(3, LENGTH(v_Next::TEXT)), '0'),
        p_Name, p_Email, p_Phone, p_Position, p_Department,
        COALESCE(p_JoiningDate, CURRENT_DATE), p_BaseSalary,
        CASE WHEN p_CTC IS NULL OR p_CTC = 0 THEN p_BaseSalary * 12 ELSE p_CTC END,
        p_Tasks, p_Address, p_EmergencyContact
    )
    RETURNING EmployeeID INTO v_ID;

    RETURN QUERY
    SELECT e.EmployeeID, e.EmployeeCode, e.Name, e.Email, e.Phone,
           e.Position, e.Department, e.JoiningDate, e.BaseSalary,
           e.CTC, e.Tasks, e.Address, e.EmergencyContact,
           e.Status, e.IsActive
    FROM Employees e
    WHERE e.EmployeeID = v_ID;
END;
$$;

CREATE OR REPLACE FUNCTION sp_AutoGeneratePayroll(p_Month VARCHAR, p_ProcessedBy INT)
RETURNS TABLE (RecordsCreated INT, Month VARCHAR)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Count INT;
BEGIN
    INSERT INTO Payrolls (EmployeeID, Month, BaseSalary, ProcessedBy)
    SELECT e.EmployeeID, p_Month, e.BaseSalary, p_ProcessedBy
    FROM Employees e
    WHERE e.IsActive = TRUE
      AND e.EmployeeID NOT IN (SELECT p.EmployeeID FROM Payrolls p WHERE p.Month = p_Month);

    GET DIAGNOSTICS v_Count = ROW_COUNT;
    RETURN QUERY SELECT v_Count, p_Month;
END;
$$;

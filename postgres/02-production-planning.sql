-- Production Planning & Quality Management.
-- PostgreSQL port of production-planning-schema.sql.
--
-- sp_GetPlanningDashboard returned five result sets, which a PostgreSQL
-- function cannot do; the production-planning service runs those five
-- queries itself.

DROP TABLE IF EXISTS QualityInspections CASCADE;
DROP TABLE IF EXISTS DailyProduction CASCADE;
DROP TABLE IF EXISTS ProductionTasks CASCADE;
DROP TABLE IF EXISTS MachineAllocations CASCADE;
DROP TABLE IF EXISTS ProductionOrders CASCADE;
DROP TABLE IF EXISTS Machines CASCADE;
DROP TABLE IF EXISTS Styles CASCADE;

CREATE TABLE Styles (
    StyleID               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StyleCode             VARCHAR(20)  UNIQUE NOT NULL,
    StyleName             VARCHAR(100) NOT NULL,
    Description           VARCHAR(500),
    Category              VARCHAR(50),  -- T-Shirt, Jeans, Dress, etc.
    EstimatedTimePerPiece INT,          -- minutes per piece
    MaterialRequired      TEXT,         -- JSON or comma-separated
    CreatedAt             TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE Machines (
    MachineID       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MachineCode     VARCHAR(20)  UNIQUE NOT NULL,
    MachineName     VARCHAR(100) NOT NULL,
    MachineType     VARCHAR(50),                   -- Cutting, Sewing, Finishing, etc.
    Status          VARCHAR(20) DEFAULT 'Available', -- Available, Occupied, Maintenance
    Location        VARCHAR(100),
    CapacityPerHour INT DEFAULT 0,
    IsActive        BOOLEAN DEFAULT TRUE,
    CreatedAt       TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE ProductionOrders (
    OrderID           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderCode         VARCHAR(20) UNIQUE NOT NULL,
    StyleID           INT REFERENCES Styles(StyleID),
    ClientName        VARCHAR(100) NOT NULL,
    TotalQuantity     INT NOT NULL,
    CompletedQuantity INT DEFAULT 0,
    StartDate         DATE,
    DeadlineDate      DATE,
    Status            VARCHAR(20) DEFAULT 'Pending', -- Pending, InProgress, Completed, Cancelled
    Priority          VARCHAR(10) DEFAULT 'Medium',  -- High, Medium, Low
    CreatedAt         TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE MachineAllocations (
    AllocationID  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MachineID     INT REFERENCES Machines(MachineID),
    EmployeeID    INT REFERENCES Employees(EmployeeID),
    OrderID       INT REFERENCES ProductionOrders(OrderID),
    AllocatedDate DATE DEFAULT CURRENT_DATE,
    ShiftTime     VARCHAR(20),                 -- Morning, Evening, Night
    Status        VARCHAR(20) DEFAULT 'Active', -- Active, Completed, Paused
    CreatedAt     TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE ProductionTasks (
    TaskID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AllocationID    INT REFERENCES MachineAllocations(AllocationID),
    TaskDate        DATE DEFAULT CURRENT_DATE,
    TargetPieces    INT NOT NULL,
    CompletedPieces INT DEFAULT 0,
    Status          VARCHAR(20) DEFAULT 'Assigned', -- Assigned, InProgress, Completed
    StartTime       TIMESTAMP,
    EndTime         TIMESTAMP,
    Notes           VARCHAR(500),
    CreatedAt       TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE DailyProduction (
    ProductionID    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TaskID          INT REFERENCES ProductionTasks(TaskID),
    EmployeeID      INT REFERENCES Employees(EmployeeID),
    MachineID       INT REFERENCES Machines(MachineID),
    OrderID         INT REFERENCES ProductionOrders(OrderID),
    ProductionDate  DATE DEFAULT CURRENT_DATE,
    PiecesCompleted INT NOT NULL,
    QualityStatus   VARCHAR(20) DEFAULT 'Pending', -- Pending, ReadyForInspection, Approved, Rejected
    ShiftTime       VARCHAR(20),
    RecordedAt      TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE QualityInspections (
    InspectionID    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductionID    INT REFERENCES DailyProduction(ProductionID),
    InspectorID     INT REFERENCES Employees(EmployeeID),
    InspectionDate  DATE DEFAULT CURRENT_DATE,
    PiecesInspected INT NOT NULL,
    PiecesApproved  INT DEFAULT 0,
    PiecesRejected  INT DEFAULT 0,
    DefectTypes     VARCHAR(500),  -- JSON or comma-separated
    InspectionNotes VARCHAR(1000),
    Status          VARCHAR(20) DEFAULT 'Completed', -- Pending, Completed
    CreatedAt       TIMESTAMP DEFAULT LOCALTIMESTAMP
);


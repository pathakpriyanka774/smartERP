-- Views for the planning manager dashboard.
CREATE VIEW vw_ProductionOverview AS
SELECT
    po.OrderCode,
    po.ClientName,
    s.StyleName,
    po.TotalQuantity,
    po.CompletedQuantity,
    po.DeadlineDate,
    po.Priority,
    po.Status AS OrderStatus,
    (po.DeadlineDate - CURRENT_DATE) AS DaysRemaining,
    CAST((po.CompletedQuantity * 100.0 / po.TotalQuantity) AS DECIMAL(5,2)) AS CompletionPercentage
FROM ProductionOrders po
JOIN Styles s ON po.StyleID = s.StyleID
WHERE po.Status != 'Cancelled';

CREATE VIEW vw_MachineStatus AS
SELECT
    m.MachineCode,
    m.MachineName,
    m.MachineType,
    m.Status,
    m.Location,
    e.Name AS AssignedEmployee,
    po.OrderCode AS CurrentOrder,
    ma.ShiftTime
FROM Machines m
LEFT JOIN MachineAllocations ma ON m.MachineID = ma.MachineID AND ma.Status = 'Active'
LEFT JOIN Employees e ON ma.EmployeeID = e.EmployeeID
LEFT JOIN ProductionOrders po ON ma.OrderID = po.OrderID;

CREATE VIEW vw_DailyProductionSummary AS
SELECT
    dp.ProductionDate,
    e.Name AS EmployeeName,
    m.MachineName,
    po.OrderCode,
    s.StyleName,
    SUM(dp.PiecesCompleted) AS TotalPieces,
    dp.QualityStatus,
    COUNT(*) AS RecordCount
FROM DailyProduction dp
JOIN Employees e ON dp.EmployeeID = e.EmployeeID
JOIN Machines m ON dp.MachineID = m.MachineID
JOIN ProductionOrders po ON dp.OrderID = po.OrderID
JOIN Styles s ON po.StyleID = s.StyleID
GROUP BY dp.ProductionDate, e.Name, m.MachineName, po.OrderCode, s.StyleName, dp.QualityStatus;

CREATE VIEW vw_QualityInspectionSummary AS
SELECT
    qi.InspectionDate,
    e.Name AS InspectorName,
    po.OrderCode,
    s.StyleName,
    SUM(qi.PiecesInspected) AS TotalInspected,
    SUM(qi.PiecesApproved) AS TotalApproved,
    SUM(qi.PiecesRejected) AS TotalRejected,
    CAST((SUM(qi.PiecesApproved) * 100.0 / NULLIF(SUM(qi.PiecesInspected), 0)) AS DECIMAL(5,2)) AS ApprovalRate
FROM QualityInspections qi
JOIN DailyProduction dp ON qi.ProductionID = dp.ProductionID
JOIN Employees e ON qi.InspectorID = e.EmployeeID
JOIN ProductionOrders po ON dp.OrderID = po.OrderID
JOIN Styles s ON po.StyleID = s.StyleID
GROUP BY qi.InspectionDate, e.Name, po.OrderCode, s.StyleName;

CREATE OR REPLACE FUNCTION sp_AllocateMachineToEmployee(
    p_MachineID INT, p_EmployeeID INT, p_OrderID INT, p_ShiftTime VARCHAR
)
RETURNS TABLE (Result TEXT, Message TEXT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
BEGIN
    -- Claiming the machine and checking it was free is one statement, so two
    -- concurrent allocations cannot both succeed.
    UPDATE Machines SET Status = 'Occupied'
    WHERE MachineID = p_MachineID AND Status = 'Available';

    IF NOT FOUND THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Machine not available'::TEXT;
        RETURN;
    END IF;

    INSERT INTO MachineAllocations (MachineID, EmployeeID, OrderID, ShiftTime)
    VALUES (p_MachineID, p_EmployeeID, p_OrderID, p_ShiftTime);

    RETURN QUERY SELECT 'Success'::TEXT, 'Machine allocated successfully'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION sp_CreateDailyTask(
    p_AllocationID INT, p_TargetPieces INT, p_TaskDate DATE DEFAULT NULL
)
RETURNS TABLE (TaskID INT, TargetPieces INT, TaskDate DATE, Status VARCHAR)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
BEGIN
    RETURN QUERY
    INSERT INTO ProductionTasks (AllocationID, TaskDate, TargetPieces)
    VALUES (p_AllocationID, COALESCE(p_TaskDate, CURRENT_DATE), p_TargetPieces)
    RETURNING ProductionTasks.TaskID, ProductionTasks.TargetPieces,
              ProductionTasks.TaskDate, ProductionTasks.Status;
END;
$$;

CREATE OR REPLACE FUNCTION sp_RecordProduction(
    p_TaskID INT, p_PiecesCompleted INT, p_Notes VARCHAR DEFAULT NULL
)
RETURNS TABLE (Result TEXT, Message TEXT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_AllocationID INT;
    v_EmployeeID   INT;
    v_MachineID    INT;
    v_OrderID      INT;
    v_ShiftTime    VARCHAR(20);
BEGIN
    SELECT pt.AllocationID INTO v_AllocationID FROM ProductionTasks pt WHERE pt.TaskID = p_TaskID;
    SELECT ma.EmployeeID, ma.MachineID, ma.OrderID, ma.ShiftTime
      INTO v_EmployeeID, v_MachineID, v_OrderID, v_ShiftTime
    FROM MachineAllocations ma WHERE ma.AllocationID = v_AllocationID;

    UPDATE ProductionTasks
    SET CompletedPieces = CompletedPieces + p_PiecesCompleted,
        Status = CASE WHEN CompletedPieces + p_PiecesCompleted >= TargetPieces
                      THEN 'Completed' ELSE 'InProgress' END,
        Notes = p_Notes
    WHERE TaskID = p_TaskID;

    -- Recorded output goes straight onto the quality queue: without this the
    -- QualityStatus default of 'Pending' means a batch never appears in
    -- /quality/pending, which filters on 'ReadyForInspection'.
    IF v_AllocationID IS NOT NULL THEN
        INSERT INTO DailyProduction (TaskID, EmployeeID, MachineID, OrderID, PiecesCompleted, ShiftTime, QualityStatus)
        VALUES (p_TaskID, v_EmployeeID, v_MachineID, v_OrderID, p_PiecesCompleted, v_ShiftTime, 'ReadyForInspection');
    END IF;

    UPDATE ProductionOrders
    SET CompletedQuantity = CompletedQuantity + p_PiecesCompleted
    WHERE OrderID = v_OrderID;

    RETURN QUERY SELECT 'Success'::TEXT, 'Production recorded successfully'::TEXT;
END;
$$;

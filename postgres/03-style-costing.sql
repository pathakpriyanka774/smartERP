CREATE TABLE Materials (
    MaterialID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaterialCode VARCHAR(20)  UNIQUE NOT NULL,
    MaterialName VARCHAR(100) NOT NULL,
    Category     VARCHAR(50),  -- Fabric, Thread, Button, Zipper, etc.
    Unit         VARCHAR(20),  -- Meter, Piece, Kg, etc.
    CurrentRate  DECIMAL(10,2) NOT NULL,
    Supplier     VARCHAR(100),
    IsActive     BOOLEAN DEFAULT TRUE,
    CreatedAt    TIMESTAMP DEFAULT LOCALTIMESTAMP
);

-- Historical pricing.
CREATE TABLE MaterialCosts (
    CostID        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaterialID    INT REFERENCES Materials(MaterialID),
    Rate          DECIMAL(10,2) NOT NULL,
    EffectiveDate DATE DEFAULT CURRENT_DATE,
    Supplier      VARCHAR(100),
    CreatedAt     TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE StyleCostings (
    CostingID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StyleID     INT REFERENCES Styles(StyleID),
    MaterialID  INT REFERENCES Materials(MaterialID),
    Quantity    DECIMAL(8,2)  NOT NULL, -- quantity required per piece
    Rate        DECIMAL(10,2) NOT NULL, -- rate at time of costing
    TotalCost   DECIMAL(18,4) GENERATED ALWAYS AS (Quantity * Rate) STORED,
    CostingDate DATE DEFAULT CURRENT_DATE,
    CreatedBy   INT,
    IsActive    BOOLEAN DEFAULT TRUE,
    CreatedAt   TIMESTAMP DEFAULT LOCALTIMESTAMP
);


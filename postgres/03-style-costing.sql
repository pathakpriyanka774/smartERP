CREATE VIEW vw_StyleCostBreakdown AS
SELECT
    s.StyleCode,
    s.StyleName,
    s.Category,
    m.MaterialName,
    m.Category AS MaterialCategory,
    sc.Quantity,
    m.Unit,
    sc.Rate,
    sc.TotalCost,
    sc.CostingDate
FROM StyleCostings sc
JOIN Styles s ON sc.StyleID = s.StyleID
JOIN Materials m ON sc.MaterialID = m.MaterialID
WHERE sc.IsActive = TRUE;

CREATE VIEW vw_StyleTotalCost AS
SELECT
    s.StyleID,
    s.StyleCode,
    s.StyleName,
    s.Category,
    SUM(sc.TotalCost) AS TotalMaterialCost,
    COUNT(sc.CostingID) AS MaterialCount,
    MAX(sc.CostingDate) AS LastUpdated
FROM Styles s
LEFT JOIN StyleCostings sc ON s.StyleID = sc.StyleID AND sc.IsActive = TRUE
GROUP BY s.StyleID, s.StyleCode, s.StyleName, s.Category;

CREATE VIEW vw_MaterialUsage AS
SELECT
    m.MaterialCode,
    m.MaterialName,
    m.Category,
    m.CurrentRate,
    COUNT(sc.CostingID) AS UsedInStyles,
    SUM(sc.Quantity) AS TotalQuantityUsed,
    AVG(sc.Rate) AS AverageRate
FROM Materials m
LEFT JOIN StyleCostings sc ON m.MaterialID = sc.MaterialID AND sc.IsActive = TRUE
GROUP BY m.MaterialID, m.MaterialCode, m.MaterialName, m.Category, m.CurrentRate;

CREATE OR REPLACE FUNCTION sp_UpdateStyleCosting(
    p_StyleID INT, p_MaterialID INT, p_Quantity DECIMAL, p_Rate DECIMAL, p_CreatedBy INT
)
RETURNS TABLE (Result TEXT, Message TEXT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
BEGIN
    -- Deactivate the existing costing for this style-material combination.
    UPDATE StyleCostings SET IsActive = FALSE
    WHERE StyleID = p_StyleID AND MaterialID = p_MaterialID;

    INSERT INTO StyleCostings (StyleID, MaterialID, Quantity, Rate, CreatedBy)
    VALUES (p_StyleID, p_MaterialID, p_Quantity, p_Rate, p_CreatedBy);

    RETURN QUERY SELECT 'Success'::TEXT, 'Style costing updated successfully'::TEXT;
END;
$$;

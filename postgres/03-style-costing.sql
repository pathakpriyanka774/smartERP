-- Style Costing: cost management for garment styles.
-- PostgreSQL port of style-costing-schema.sql.
--
-- sp_GetStyleCosting returned a different row shape depending on its
-- argument, and sp_GetCostingDashboard returned three result sets; a
-- PostgreSQL function can do neither, so the costing service queries the
-- views directly for those.

DROP TABLE IF EXISTS StyleCostings CASCADE;
DROP TABLE IF EXISTS MaterialCosts CASCADE;
DROP TABLE IF EXISTS Materials CASCADE;

-- Normally created by 02-production-planning.sql; kept here so this file can
-- also be applied on its own.
CREATE TABLE IF NOT EXISTS Styles (
    StyleID               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    StyleCode             VARCHAR(20)  UNIQUE NOT NULL,
    StyleName             VARCHAR(100) NOT NULL,
    Description           VARCHAR(500),
    Category              VARCHAR(50),
    EstimatedTimePerPiece INT,
    MaterialRequired      TEXT,
    CreatedAt             TIMESTAMP DEFAULT LOCALTIMESTAMP
);


-- Core ERP tables: orders, inventory, finance and clients.
-- PostgreSQL port of erp-core-schema.sql.

DROP TABLE IF EXISTS FinanceTransactions CASCADE;
DROP TABLE IF EXISTS InventoryItems CASCADE;
DROP TABLE IF EXISTS Orders CASCADE;
DROP TABLE IF EXISTS Clients CASCADE;

CREATE TABLE Clients (
    ClientID  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name      VARCHAR(150) NOT NULL,
    Type      VARCHAR(50),
    Email     VARCHAR(150),
    Phone     VARCHAR(30),
    Status    VARCHAR(20) DEFAULT 'active',
    CreatedAt TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE Orders (
    OrderID      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ClientName   VARCHAR(150) NOT NULL,
    OrderDate    DATE DEFAULT CURRENT_DATE,
    DeliveryDate DATE,
    Status       VARCHAR(30) DEFAULT 'pending',
    Priority     VARCHAR(20) DEFAULT 'medium',
    TotalAmount  DECIMAL(14,2) DEFAULT 0,
    CreatedAt    TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE InventoryItems (
    ItemID       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ItemName     VARCHAR(150) NOT NULL,
    Category     VARCHAR(50),
    Quantity     INT DEFAULT 0,
    Unit         VARCHAR(30),
    ReorderLevel INT DEFAULT 0,
    CreatedAt    TIMESTAMP DEFAULT LOCALTIMESTAMP
);

CREATE TABLE FinanceTransactions (
    TransactionID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Type          VARCHAR(20) NOT NULL,          -- income | expense
    Amount        DECIMAL(14,2) NOT NULL,
    Description   VARCHAR(300),
    TxnDate       DATE DEFAULT CURRENT_DATE,
    Category      VARCHAR(50),
    CreatedAt     TIMESTAMP DEFAULT LOCALTIMESTAMP
);


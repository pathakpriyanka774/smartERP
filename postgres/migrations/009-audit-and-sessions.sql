-- Audit trail and immediate access revocation.

-- ------------------------------------------------------------ Audit log ---
-- Written by triggers, so every change is captured whichever service (or
-- direct SQL) makes it. The acting user comes from the session setting
-- app.user_id, which shared/database.js sets from the authenticated request.
-- Append-only: rows cannot be changed or deleted by the application.
--
-- Contains personal data (names, salaries in HR rows): readable by Admins
-- only, and covered by the retention policy in docs/erp-audit/12.
CREATE TABLE IF NOT EXISTS AuditLog (
    AuditID    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OccurredAt TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,   -- UTC, like every timestamp here
    UserID     INT,                       -- no FK: history outlives deleted users
    Action     VARCHAR(10) NOT NULL,      -- INSERT, UPDATE, DELETE, LOGIN, LOGIN_FAIL, LOGOUT
    TableName  VARCHAR(60) NOT NULL,
    RecordID   VARCHAR(60),
    OldData    JSONB,                     -- for UPDATE, only the fields that changed
    NewData    JSONB
);
CREATE INDEX IF NOT EXISTS IX_Audit_Time   ON AuditLog (OccurredAt DESC);
CREATE INDEX IF NOT EXISTS IX_Audit_Record ON AuditLog (TableName, RecordID);
CREATE INDEX IF NOT EXISTS IX_Audit_User   ON AuditLog (UserID, OccurredAt DESC);

CREATE OR REPLACE FUNCTION trg_auditlog_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'The audit log is append-only';
END;
$$;

/** The acting user for this transaction or session, or NULL (system / migration). */
CREATE OR REPLACE FUNCTION fn_CurrentActor() RETURNS INT
LANGUAGE sql STABLE AS $$
    SELECT NULLIF(current_setting('app.user_id', TRUE), '')::INT
$$;

/**
 * Generic row audit. TG_ARGV: the primary-key column(s), lower-case.
 * Secrets are never copied: password hashes are removed before logging.
 */
CREATE OR REPLACE FUNCTION trg_audit() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_Old JSONB;
    v_New JSONB;
    v_Key TEXT;
    v_ID  TEXT := '';
    v_Row JSONB;
    i     INT;
BEGIN
    IF TG_OP <> 'INSERT' THEN v_Old := to_jsonb(OLD) - 'passwordhash'; END IF;
    IF TG_OP <> 'DELETE' THEN v_New := to_jsonb(NEW) - 'passwordhash'; END IF;

    IF TG_OP = 'UPDATE' THEN
        -- Keep only what changed; skip updates that changed nothing loggable.
        FOR v_Key IN SELECT jsonb_object_keys(v_New) LOOP
            IF v_Old->v_Key IS NOT DISTINCT FROM v_New->v_Key THEN
                v_Old := v_Old - v_Key;
                v_New := v_New - v_Key;
            END IF;
        END LOOP;
        IF v_New = '{}'::JSONB THEN
            RETURN NULL;
        END IF;
    END IF;

    v_Row := COALESCE(to_jsonb(NEW), to_jsonb(OLD));
    FOR i IN 0 .. TG_NARGS - 1 LOOP
        v_ID := v_ID || CASE WHEN i > 0 THEN '/' ELSE '' END || COALESCE(v_Row->>TG_ARGV[i], '');
    END LOOP;

    INSERT INTO AuditLog (UserID, Action, TableName, RecordID, OldData, NewData)
    VALUES (fn_CurrentActor(), TG_OP, TG_TABLE_NAME, v_ID, v_Old, v_New);
    RETURN NULL;
END;
$$;

DO $$
DECLARE
    t RECORD;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'auditlog_append_only') THEN
        CREATE TRIGGER auditlog_append_only BEFORE UPDATE OR DELETE ON AuditLog
            FOR EACH ROW EXECUTE FUNCTION trg_auditlog_append_only();
    END IF;

    FOR t IN SELECT * FROM (VALUES
        ('users', 'userid'), ('userpermissions', 'userid,menukey'), ('organizationsettings', 'settingsid'),
        ('employees', 'employeeid'), ('payrolls', 'payrollid'), ('employeeattendance', 'attendanceid'),
        ('clients', 'clientid'), ('orders', 'orderid'), ('orderitems', 'orderitemid'),
        ('inventoryitems', 'itemid'), ('financetransactions', 'transactionid'),
        ('invoices', 'invoiceid'), ('payments', 'paymentid'),
        ('purchaseorders', 'poid'), ('purchaseorderitems', 'poitemid'), ('goodsreceipts', 'grnid'),
        ('supplierbills', 'billid'), ('accounts', 'accountid'),
        ('productionorders', 'orderid'), ('qualityinspections', 'inspectionid'),
        ('styles', 'styleid'), ('materials', 'materialid'), ('stylecostings', 'costingid'),
        ('appmenus', 'menuid'), ('custompages', 'pageid')
    ) AS x(tbl, pk) LOOP
        IF to_regclass(t.tbl) IS NOT NULL
           AND NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_' || t.tbl) THEN
            EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION trg_audit(%s)',
                           'audit_' || t.tbl, t.tbl,
                           (SELECT string_agg(quote_literal(k), ', ') FROM unnest(string_to_array(t.pk, ',')) k));
        END IF;
    END LOOP;
END $$;

-- -------------------------------------------------------- Revocation ---
-- Every token carries the user's TokenVersion. Each request checks it (and
-- IsActive) against this table, so bumping it ends every session at once.
-- The trigger bumps it whenever access is reduced at the source — the account
-- is deactivated, its role changes or its password is reset — so the rule
-- holds even for a change made directly in SQL.
ALTER TABLE Users ADD COLUMN IF NOT EXISTS TokenVersion INT NOT NULL DEFAULT 0;

CREATE OR REPLACE FUNCTION trg_users_token_version() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.IsActive IS DISTINCT FROM OLD.IsActive AND NOT COALESCE(NEW.IsActive, FALSE)
       OR NEW.Role IS DISTINCT FROM OLD.Role
       OR NEW.PasswordHash IS DISTINCT FROM OLD.PasswordHash THEN
        NEW.TokenVersion := OLD.TokenVersion + 1;
    END IF;
    RETURN NEW;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'users_token_version') THEN
        CREATE TRIGGER users_token_version BEFORE UPDATE ON Users
            FOR EACH ROW EXECUTE FUNCTION trg_users_token_version();
    END IF;
END $$;

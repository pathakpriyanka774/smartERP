-- Link the modules that were islands: orders ↔ clients ↔ stock, and
-- production ↔ sales orders ↔ materials ↔ finished goods.

-- ---------------------------------------------------------------- Sales ---

ALTER TABLE Orders ADD COLUMN IF NOT EXISTS ClientID INT REFERENCES Clients(ClientID) ON DELETE SET NULL;

-- Existing orders carry only a client name; link those that match exactly one client.
UPDATE Orders o SET ClientID = c.ClientID
FROM Clients c
WHERE o.ClientID IS NULL
  AND lower(c.Name) = lower(o.ClientName)
  AND (SELECT COUNT(*) FROM Clients c2 WHERE lower(c2.Name) = lower(o.ClientName)) = 1;

CREATE TABLE IF NOT EXISTS OrderItems (
    OrderItemID      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID          INT NOT NULL REFERENCES Orders(OrderID) ON DELETE CASCADE,
    ItemID           INT REFERENCES InventoryItems(ItemID),   -- NULL for a service or custom line
    Description      VARCHAR(200) NOT NULL,
    Quantity         INT NOT NULL CHECK (Quantity > 0),
    UnitPrice        DECIMAL(12,2) NOT NULL CHECK (UnitPrice >= 0),
    LineTotal        DECIMAL(16,2) GENERATED ALWAYS AS (Quantity * UnitPrice) STORED,
    -- Stock held for this line once the order is confirmed, and stock taken
    -- out when it is dispatched.
    ReservedQuantity INT NOT NULL DEFAULT 0 CHECK (ReservedQuantity >= 0),
    IssuedQuantity   INT NOT NULL DEFAULT 0 CHECK (IssuedQuantity >= 0)
);
CREATE INDEX IF NOT EXISTS IX_OrderItems_Order ON OrderItems (OrderID);
CREATE INDEX IF NOT EXISTS IX_OrderItems_Item  ON OrderItems (ItemID);
CREATE INDEX IF NOT EXISTS IX_Orders_Client    ON Orders (ClientID);

-- ----------------------------------------------------------- Production ---

ALTER TABLE ProductionOrders ADD COLUMN IF NOT EXISTS SalesOrderID INT REFERENCES Orders(OrderID) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS IX_ProductionOrders_Sales ON ProductionOrders (SalesOrderID);

-- A costing material can be tied to the stock item it is drawn from, and a
-- style to the stock item its finished garments are counted in. Both are
-- optional: an unlinked material is costed but not tracked in stock.
ALTER TABLE Materials ADD COLUMN IF NOT EXISTS InventoryItemID INT REFERENCES InventoryItems(ItemID) ON DELETE SET NULL;
ALTER TABLE Styles    ADD COLUMN IF NOT EXISTS FinishedItemID  INT REFERENCES InventoryItems(ItemID) ON DELETE SET NULL;

-- New production order codes: PRD-00001, ... (existing ORDxxx codes are kept).
CREATE SEQUENCE IF NOT EXISTS ProductionOrderCodeSeq;

-- Views gain the IDs the screens need to act on a row (the planning screen
-- read MachineID and OrderID, which these views did not return), and a wider
-- percentage type: DECIMAL(5,2) overflowed above 999.99 %.
DROP VIEW IF EXISTS vw_ProductionOverview;
CREATE VIEW vw_ProductionOverview AS
SELECT
    po.OrderCode,
    po.ClientName,
    s.StyleName,
    po.TotalQuantity,
    po.CompletedQuantity,
    po.DeadlineDate,
    po.Priority,
    po.Status AS OrderStatus,
    (po.DeadlineDate - CURRENT_DATE) AS DaysRemaining,
    CAST((po.CompletedQuantity * 100.0 / NULLIF(po.TotalQuantity, 0)) AS DECIMAL(9,2)) AS CompletionPercentage,
    po.OrderID,
    po.StyleID,
    po.SalesOrderID,
    po.StartDate
FROM ProductionOrders po
JOIN Styles s ON po.StyleID = s.StyleID
WHERE po.Status != 'Cancelled';

DROP VIEW IF EXISTS vw_MachineStatus;
CREATE VIEW vw_MachineStatus AS
SELECT
    m.MachineCode,
    m.MachineName,
    m.MachineType,
    m.Status,
    m.Location,
    e.Name AS AssignedEmployee,
    po.OrderCode AS CurrentOrder,
    ma.ShiftTime,
    m.MachineID,
    ma.AllocationID
FROM Machines m
LEFT JOIN MachineAllocations ma ON m.MachineID = ma.MachineID AND ma.Status = 'Active'
LEFT JOIN Employees e ON ma.EmployeeID = e.EmployeeID
LEFT JOIN ProductionOrders po ON ma.OrderID = po.OrderID;

/**
 * Record output against a task.
 *
 * Refuses pieces beyond what the task and the production order still need,
 * moves the order to InProgress / Completed, and consumes the materials of the
 * style's active costing from their linked stock items. If any material is
 * short, sp_StockMove raises and the whole recording rolls back.
 */
CREATE OR REPLACE FUNCTION sp_RecordProduction(
    p_TaskID INT, p_PiecesCompleted INT, p_Notes VARCHAR DEFAULT NULL, p_RecordedBy INT DEFAULT NULL,
    -- The business date (India), passed by the service; the session runs in UTC.
    p_BusinessDate DATE DEFAULT NULL
)
RETURNS TABLE (Result TEXT, Message TEXT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Task        RECORD;
    v_Alloc       RECORD;
    v_Order       RECORD;
    v_ProdID      INT;
    v_Mat         RECORD;
    v_Need        INT;
BEGIN
    IF p_PiecesCompleted IS NULL OR p_PiecesCompleted <= 0 THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Pieces completed must be a positive number'::TEXT;
        RETURN;
    END IF;

    -- Lock the task and its order so two recordings cannot both pass the checks.
    SELECT pt.* INTO v_Task FROM ProductionTasks pt WHERE pt.TaskID = p_TaskID FOR UPDATE;
    IF NOT FOUND THEN
        RETURN QUERY SELECT 'Error'::TEXT, 'Task not found'::TEXT;
        RETURN;
    END IF;
    SELECT ma.* INTO v_Alloc FROM MachineAllocations ma WHERE ma.AllocationID = v_Task.AllocationID;
    SELECT po.* INTO v_Order FROM ProductionOrders po WHERE po.OrderID = v_Alloc.OrderID FOR UPDATE;

    IF p_PiecesCompleted > v_Task.TargetPieces - v_Task.CompletedPieces THEN
        RETURN QUERY SELECT 'Error'::TEXT,
            format('Only %s pieces remain on this task (target %s, done %s)',
                   v_Task.TargetPieces - v_Task.CompletedPieces, v_Task.TargetPieces, v_Task.CompletedPieces);
        RETURN;
    END IF;
    IF v_Order.OrderID IS NOT NULL AND p_PiecesCompleted > v_Order.TotalQuantity - v_Order.CompletedQuantity THEN
        RETURN QUERY SELECT 'Error'::TEXT,
            format('Only %s pieces remain on production order %s', v_Order.TotalQuantity - v_Order.CompletedQuantity, v_Order.OrderCode);
        RETURN;
    END IF;

    UPDATE ProductionTasks
    SET CompletedPieces = CompletedPieces + p_PiecesCompleted,
        Status = CASE WHEN CompletedPieces + p_PiecesCompleted >= TargetPieces THEN 'Completed' ELSE 'InProgress' END,
        StartTime = COALESCE(StartTime, LOCALTIMESTAMP),
        EndTime = CASE WHEN CompletedPieces + p_PiecesCompleted >= TargetPieces THEN LOCALTIMESTAMP ELSE EndTime END,
        Notes = COALESCE(p_Notes, Notes)
    WHERE TaskID = p_TaskID;

    -- Recorded output goes straight onto the quality queue.
    INSERT INTO DailyProduction (TaskID, EmployeeID, MachineID, OrderID, ProductionDate, PiecesCompleted, ShiftTime, QualityStatus)
    VALUES (p_TaskID, v_Alloc.EmployeeID, v_Alloc.MachineID, v_Alloc.OrderID, COALESCE(p_BusinessDate, CURRENT_DATE),
            p_PiecesCompleted, v_Alloc.ShiftTime, 'ReadyForInspection')
    RETURNING ProductionID INTO v_ProdID;

    IF v_Order.OrderID IS NOT NULL THEN
        UPDATE ProductionOrders
        SET CompletedQuantity = CompletedQuantity + p_PiecesCompleted,
            Status = CASE WHEN CompletedQuantity + p_PiecesCompleted >= TotalQuantity THEN 'Completed' ELSE 'InProgress' END,
            StartDate = COALESCE(StartDate, p_BusinessDate, CURRENT_DATE)
        WHERE OrderID = v_Order.OrderID;

        -- Material consumption from the style's bill of materials (active costing).
        FOR v_Mat IN
            SELECT m.InventoryItemID, m.MaterialName, sc.Quantity AS PerPiece
            FROM StyleCostings sc
            JOIN Materials m ON m.MaterialID = sc.MaterialID
            WHERE sc.StyleID = v_Order.StyleID AND sc.IsActive = TRUE AND m.InventoryItemID IS NOT NULL
        LOOP
            v_Need := CEIL(v_Mat.PerPiece * p_PiecesCompleted);
            IF v_Need > 0 THEN
                PERFORM sp_StockMove(v_Mat.InventoryItemID, 'consumption', -v_Need, NULL,
                                     format('%s: %s pcs', v_Order.OrderCode, p_PiecesCompleted),
                                     'production', v_ProdID, v_Mat.MaterialName, p_RecordedBy);
            END IF;
        END LOOP;
    END IF;

    RETURN QUERY SELECT 'Success'::TEXT, 'Production recorded successfully'::TEXT;
END;
$$;

-- The old 3-argument signature would otherwise remain as a second overload.
DROP FUNCTION IF EXISTS sp_RecordProduction(INT, INT, VARCHAR);

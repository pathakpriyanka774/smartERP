-- GST tax invoices from sales orders, and customer receipts against them.
--
-- Invoices are numbered gaplessly per financial year (sp_NextDocNumber in
-- migration 005), stored with a snapshot of seller and buyer details, and
-- cannot be edited once issued: a mistake is corrected by cancelling (the
-- number is kept, marked cancelled) and issuing a new one.

-- --------------------------------------------------- Party tax details ---
ALTER TABLE Clients ADD COLUMN IF NOT EXISTS GSTIN        VARCHAR(15);
ALTER TABLE Clients ADD COLUMN IF NOT EXISTS StateCode    CHAR(2);
ALTER TABLE Clients ADD COLUMN IF NOT EXISTS Address      VARCHAR(300);
ALTER TABLE Clients ADD COLUMN IF NOT EXISTS City         VARCHAR(100);
ALTER TABLE Clients ADD COLUMN IF NOT EXISTS Pincode      VARCHAR(10);
ALTER TABLE Clients ADD COLUMN IF NOT EXISTS PaymentTermsDays INT;

-- ---------------------------------------------------- Item tax details ---
ALTER TABLE InventoryItems ADD COLUMN IF NOT EXISTS HSNCode VARCHAR(8);
ALTER TABLE InventoryItems ADD COLUMN IF NOT EXISTS GSTRate DECIMAL(5,2);
ALTER TABLE OrderItems     ADD COLUMN IF NOT EXISTS HSNCode VARCHAR(8);
ALTER TABLE OrderItems     ADD COLUMN IF NOT EXISTS GSTRate DECIMAL(5,2);
ALTER TABLE OrderItems     ADD COLUMN IF NOT EXISTS InvoicedQuantity INT NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_orderitems_invoiced') THEN
        ALTER TABLE OrderItems ADD CONSTRAINT CK_OrderItems_Invoiced CHECK (InvoicedQuantity BETWEEN 0 AND Quantity);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_inventory_gstrate') THEN
        ALTER TABLE InventoryItems ADD CONSTRAINT CK_Inventory_GSTRate CHECK (GSTRate IS NULL OR GSTRate BETWEEN 0 AND 40);
        ALTER TABLE OrderItems ADD CONSTRAINT CK_OrderItems_GSTRate CHECK (GSTRate IS NULL OR GSTRate BETWEEN 0 AND 40);
    END IF;
END $$;

-- ------------------------------------------------------------ Invoices ---
CREATE TABLE IF NOT EXISTS Invoices (
    InvoiceID      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    InvoiceNumber  VARCHAR(16) NOT NULL UNIQUE,
    FinancialYear  VARCHAR(5)  NOT NULL,
    SequenceNo     INT         NOT NULL,
    InvoiceDate    DATE        NOT NULL,
    DueDate        DATE        NOT NULL,
    OrderID        INT REFERENCES Orders(OrderID),
    ClientID       INT REFERENCES Clients(ClientID),
    BuyerName      VARCHAR(150) NOT NULL,
    BuyerGSTIN     VARCHAR(15),
    BuyerAddress   VARCHAR(400),
    PlaceOfSupply  CHAR(2)     NOT NULL,          -- GST state code
    SupplyType     VARCHAR(5)  NOT NULL CHECK (SupplyType IN ('intra', 'inter')),
    Seller         JSONB       NOT NULL,          -- seller details as printed, frozen at issue
    TaxableValue   DECIMAL(16,2) NOT NULL,
    CGST           DECIMAL(16,2) NOT NULL DEFAULT 0,
    SGST           DECIMAL(16,2) NOT NULL DEFAULT 0,
    IGST           DECIMAL(16,2) NOT NULL DEFAULT 0,
    RoundOff       DECIMAL(6,2)  NOT NULL DEFAULT 0,
    GrandTotal     DECIMAL(16,2) NOT NULL,
    AmountPaid     DECIMAL(16,2) NOT NULL DEFAULT 0,
    Status         VARCHAR(15) NOT NULL DEFAULT 'issued'
                   CHECK (Status IN ('issued', 'partially-paid', 'paid', 'cancelled')),
    Notes          VARCHAR(500),
    EntryID        INT REFERENCES JournalEntries(EntryID),
    CancelledAt    TIMESTAMP,
    CancelledBy    INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CancelReason   VARCHAR(300),
    CancelEntryID  INT REFERENCES JournalEntries(EntryID),
    CreatedBy      INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt      TIMESTAMP DEFAULT LOCALTIMESTAMP,
    CONSTRAINT UQ_Invoices_Sequence UNIQUE (FinancialYear, SequenceNo),
    CONSTRAINT CK_Invoices_Totals CHECK (
        GrandTotal = TaxableValue + CGST + SGST + IGST + RoundOff
        AND (SupplyType = 'intra' OR (CGST = 0 AND SGST = 0))
        AND (SupplyType = 'inter' OR IGST = 0)
        AND ABS(RoundOff) < 1),
    CONSTRAINT CK_Invoices_Paid CHECK (AmountPaid >= 0 AND AmountPaid <= GrandTotal),
    CONSTRAINT CK_Invoices_Due CHECK (DueDate >= InvoiceDate)
);
CREATE INDEX IF NOT EXISTS IX_Invoices_Client ON Invoices (ClientID);
CREATE INDEX IF NOT EXISTS IX_Invoices_Order  ON Invoices (OrderID);
CREATE INDEX IF NOT EXISTS IX_Invoices_Date   ON Invoices (InvoiceDate);

CREATE TABLE IF NOT EXISTS InvoiceItems (
    InvoiceItemID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    InvoiceID     INT NOT NULL REFERENCES Invoices(InvoiceID),
    OrderItemID   INT REFERENCES OrderItems(OrderItemID),
    Description   VARCHAR(200) NOT NULL,
    HSNCode       VARCHAR(8),
    Quantity      INT NOT NULL CHECK (Quantity > 0),
    Unit          VARCHAR(30),
    UnitPrice     DECIMAL(12,2) NOT NULL CHECK (UnitPrice >= 0),
    TaxableValue  DECIMAL(16,2) NOT NULL,
    GSTRate       DECIMAL(5,2)  NOT NULL CHECK (GSTRate BETWEEN 0 AND 40),
    CGST          DECIMAL(16,2) NOT NULL DEFAULT 0,
    SGST          DECIMAL(16,2) NOT NULL DEFAULT 0,
    IGST          DECIMAL(16,2) NOT NULL DEFAULT 0,
    LineTotal     DECIMAL(16,2) NOT NULL,
    CONSTRAINT CK_InvoiceItems_Total CHECK (LineTotal = TaxableValue + CGST + SGST + IGST)
);
CREATE INDEX IF NOT EXISTS IX_InvoiceItems_Invoice ON InvoiceItems (InvoiceID);

-- An issued invoice is a legal document: its amounts, parties and lines never
-- change. Only payment progress and cancellation may be recorded on it.
CREATE OR REPLACE FUNCTION trg_invoice_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Issued invoices cannot be deleted; cancel them instead';
    END IF;
    IF (NEW.InvoiceNumber, NEW.InvoiceDate, NEW.DueDate, NEW.ClientID, NEW.OrderID, NEW.BuyerName, NEW.BuyerGSTIN,
        NEW.BuyerAddress, NEW.PlaceOfSupply, NEW.SupplyType, NEW.Seller, NEW.TaxableValue, NEW.CGST, NEW.SGST, NEW.IGST,
        NEW.RoundOff, NEW.GrandTotal)
       IS DISTINCT FROM
       (OLD.InvoiceNumber, OLD.InvoiceDate, OLD.DueDate, OLD.ClientID, OLD.OrderID, OLD.BuyerName, OLD.BuyerGSTIN,
        OLD.BuyerAddress, OLD.PlaceOfSupply, OLD.SupplyType, OLD.Seller, OLD.TaxableValue, OLD.CGST, OLD.SGST, OLD.IGST,
        OLD.RoundOff, OLD.GrandTotal)
       OR (OLD.EntryID IS NOT NULL AND NEW.EntryID IS DISTINCT FROM OLD.EntryID) THEN
        RAISE EXCEPTION 'Issued invoices cannot be edited; cancel and re-issue instead';
    END IF;
    IF OLD.Status = 'cancelled' THEN
        RAISE EXCEPTION 'Invoice % is cancelled', OLD.InvoiceNumber;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION trg_invoice_items_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Invoice lines cannot be changed once issued';
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'invoices_immutable') THEN
        CREATE TRIGGER invoices_immutable BEFORE UPDATE OR DELETE ON Invoices
            FOR EACH ROW EXECUTE FUNCTION trg_invoice_immutable();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'invoice_items_immutable') THEN
        CREATE TRIGGER invoice_items_immutable BEFORE UPDATE OR DELETE ON InvoiceItems
            FOR EACH ROW EXECUTE FUNCTION trg_invoice_items_immutable();
    END IF;
END $$;

-- ------------------------------------------------------------ Payments ---
-- Money received from customers ('in') or paid to suppliers ('out'), each
-- against one document. Posted payments are voided, never edited.
CREATE TABLE IF NOT EXISTS Payments (
    PaymentID     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PaymentNumber VARCHAR(16) NOT NULL UNIQUE,
    Direction     VARCHAR(3)  NOT NULL CHECK (Direction IN ('in', 'out')),
    PartyID       INT REFERENCES Clients(ClientID),
    InvoiceID     INT REFERENCES Invoices(InvoiceID),
    PaymentDate   DATE        NOT NULL,
    Amount        DECIMAL(16,2) NOT NULL CHECK (Amount > 0),
    Method        VARCHAR(10) NOT NULL CHECK (Method IN ('bank', 'cash', 'upi', 'cheque', 'card')),
    Reference     VARCHAR(100),
    Notes         VARCHAR(300),
    Status        VARCHAR(10) NOT NULL DEFAULT 'posted' CHECK (Status IN ('posted', 'void')),
    EntryID       INT REFERENCES JournalEntries(EntryID),
    VoidEntryID   INT REFERENCES JournalEntries(EntryID),
    VoidedAt      TIMESTAMP,
    VoidedBy      INT REFERENCES Users(UserID) ON DELETE SET NULL,
    VoidReason    VARCHAR(300),
    CreatedBy     INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt     TIMESTAMP DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_Payments_Invoice ON Payments (InvoiceID);
CREATE INDEX IF NOT EXISTS IX_Payments_Party   ON Payments (PartyID);
CREATE INDEX IF NOT EXISTS IX_Payments_Date    ON Payments (PaymentDate);

-- Stock list shows each item's tax details (new columns go at the end, so
-- CREATE OR REPLACE keeps the view's existing columns as they are).
CREATE OR REPLACE VIEW vw_InventoryStatus AS
SELECT
    ItemID, ItemName, Category, Quantity, Unit, ReorderLevel,
    CASE
        WHEN Quantity <= 0 THEN 'out-of-stock'
        WHEN Quantity <= ReorderLevel THEN 'low-stock'
        ELSE 'in-stock'
    END AS Status,
    SKU,
    UnitCost,
    ReservedQuantity,
    Quantity - ReservedQuantity AS AvailableQuantity,
    CAST(Quantity * UnitCost AS DECIMAL(16,2)) AS TotalValue,
    HSNCode,
    GSTRate
FROM InventoryItems;

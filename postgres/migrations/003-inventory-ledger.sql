-- Item cost, stock movement history and stock value.
--
-- Stock quantity used to be overwritten directly, so it had no history, two
-- people updating at once overwrote each other, and with no cost there was no
-- stock value. Every change now goes through sp_StockMove, which adjusts the
-- quantity atomically, keeps a weighted-average unit cost, and writes one
-- StockMovements row explaining the change.

ALTER TABLE InventoryItems ADD COLUMN IF NOT EXISTS SKU VARCHAR(40);
ALTER TABLE InventoryItems ADD COLUMN IF NOT EXISTS UnitCost DECIMAL(12,2) NOT NULL DEFAULT 0;
-- Held for confirmed sales orders: on hand, but not free to use elsewhere.
ALTER TABLE InventoryItems ADD COLUMN IF NOT EXISTS ReservedQuantity INT NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS UQ_InventoryItems_SKU ON InventoryItems (SKU) WHERE SKU IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_inventory_cost') THEN
        ALTER TABLE InventoryItems ADD CONSTRAINT CK_Inventory_Cost CHECK (UnitCost >= 0) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_inventory_reserved') THEN
        ALTER TABLE InventoryItems ADD CONSTRAINT CK_Inventory_Reserved
            CHECK (ReservedQuantity >= 0 AND ReservedQuantity <= Quantity) NOT VALID;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS StockMovements (
    MovementID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ItemID       INT NOT NULL REFERENCES InventoryItems(ItemID),
    -- opening: balance when the ledger started; receipt: goods in;
    -- issue: goods out (manual); adjustment: count correction (+/-);
    -- consumption: used by production; production: finished goods made;
    -- sale: dispatched against a sales order.
    MovementType VARCHAR(20) NOT NULL
        CHECK (MovementType IN ('opening','receipt','issue','adjustment','consumption','production','sale')),
    Quantity     INT NOT NULL CHECK (Quantity <> 0),      -- signed: positive in, negative out
    UnitCost     DECIMAL(12,2),
    BalanceAfter INT NOT NULL,
    Reference    VARCHAR(100),
    SourceType   VARCHAR(30),                             -- 'order', 'production', 'inspection', ...
    SourceID     INT,
    Notes        VARCHAR(300),
    CreatedBy    INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt    TIMESTAMP DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_StockMovements_Item   ON StockMovements (ItemID, MovementID);
CREATE INDEX IF NOT EXISTS IX_StockMovements_Source ON StockMovements (SourceType, SourceID);

-- Stock that existed before the ledger gets an opening entry, so the history
-- always adds up to the quantity on hand.
INSERT INTO StockMovements (ItemID, MovementType, Quantity, UnitCost, BalanceAfter, Reference)
SELECT i.ItemID, 'opening', i.Quantity, i.UnitCost, i.Quantity, 'Opening balance when stock history started'
FROM InventoryItems i
WHERE i.Quantity > 0
  AND NOT EXISTS (SELECT 1 FROM StockMovements m WHERE m.ItemID = i.ItemID);

/**
 * The one way stock changes.
 *
 * Applies a signed quantity in a single UPDATE, so concurrent movements add up
 * instead of overwriting each other, and refuses to take stock below zero or
 * below what is reserved for orders. A sale dispatching reserved stock first
 * releases its own reservation in the same transaction, so it can never use
 * stock that another order holds.
 *
 * Incoming stock with a cost updates the weighted-average unit cost:
 *   new cost = (on hand × cost + received × received cost) ÷ (on hand + received)
 *
 * Raises P0001 with a readable message when stock is insufficient, so a
 * multi-line operation in one transaction rolls back as a whole.
 */
CREATE OR REPLACE FUNCTION sp_StockMove(
    p_ItemID     INT,
    p_Type       VARCHAR,
    p_Quantity   INT,
    p_UnitCost   DECIMAL DEFAULT NULL,
    p_Reference  VARCHAR DEFAULT NULL,
    p_SourceType VARCHAR DEFAULT NULL,
    p_SourceID   INT     DEFAULT NULL,
    p_Notes      VARCHAR DEFAULT NULL,
    p_CreatedBy  INT     DEFAULT NULL
)
RETURNS TABLE (MovementID INT, ItemID INT, BalanceAfter INT, UnitCost DECIMAL)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Balance  INT;
    v_Cost     DECIMAL(12,2);
    v_Name     VARCHAR(150);
    v_OnHand   INT;
    v_Reserved INT;
BEGIN
    IF p_Quantity IS NULL OR p_Quantity = 0 THEN
        RAISE EXCEPTION 'Quantity must not be zero';
    END IF;

    UPDATE InventoryItems i
    SET Quantity = i.Quantity + p_Quantity,
        UnitCost = CASE
            WHEN p_Quantity > 0 AND p_UnitCost IS NOT NULL AND i.Quantity + p_Quantity > 0
            THEN ROUND((GREATEST(i.Quantity, 0) * i.UnitCost + p_Quantity * p_UnitCost)
                       / (GREATEST(i.Quantity, 0) + p_Quantity), 2)
            ELSE i.UnitCost END
    WHERE i.ItemID = p_ItemID
      AND i.Quantity + p_Quantity >= 0
      AND (p_Quantity > 0 OR i.Quantity + p_Quantity >= i.ReservedQuantity)
    RETURNING i.Quantity, i.UnitCost INTO v_Balance, v_Cost;

    IF NOT FOUND THEN
        SELECT i.ItemName, i.Quantity, i.ReservedQuantity INTO v_Name, v_OnHand, v_Reserved
        FROM InventoryItems i WHERE i.ItemID = p_ItemID;
        IF v_Name IS NULL THEN
            RAISE EXCEPTION 'Stock item % does not exist', p_ItemID;
        END IF;
        RAISE EXCEPTION 'Not enough stock of "%": % on hand, % reserved, % requested',
            v_Name, v_OnHand, v_Reserved, -p_Quantity;
    END IF;

    RETURN QUERY
    INSERT INTO StockMovements (ItemID, MovementType, Quantity, UnitCost, BalanceAfter,
                                Reference, SourceType, SourceID, Notes, CreatedBy)
    VALUES (p_ItemID, p_Type, p_Quantity, COALESCE(p_UnitCost, v_Cost), v_Balance,
            p_Reference, p_SourceType, p_SourceID, p_Notes, p_CreatedBy)
    RETURNING StockMovements.MovementID, StockMovements.ItemID, StockMovements.BalanceAfter, v_Cost;
END;
$$;

-- Status derived from quantity vs reorder level, now with cost and value.
DROP VIEW IF EXISTS vw_InventoryStatus;
CREATE VIEW vw_InventoryStatus AS
SELECT
    ItemID, ItemName, Category, Quantity, Unit, ReorderLevel,
    CASE
        WHEN Quantity <= 0 THEN 'out-of-stock'
        WHEN Quantity <= ReorderLevel THEN 'low-stock'
        ELSE 'in-stock'
    END AS Status,
    SKU,
    UnitCost,
    ReservedQuantity,
    Quantity - ReservedQuantity AS AvailableQuantity,
    CAST(Quantity * UnitCost AS DECIMAL(16,2)) AS TotalValue
FROM InventoryItems;

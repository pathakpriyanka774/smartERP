-- A unit-cost edit (not through sp_StockMove, which always changes the
-- quantity) revalues the stock on hand, so the ledger follows. Giving a cost
-- to stock that had none is an opening balance, not an expense.
CREATE OR REPLACE FUNCTION trg_inventory_revalue() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_Value DECIMAL(16,2);
    v_Other VARCHAR(10);
BEGIN
    IF NEW.Quantity = OLD.Quantity AND NEW.Quantity > 0
       AND COALESCE(NEW.UnitCost, 0) <> COALESCE(OLD.UnitCost, 0) THEN
        v_Value := ROUND(NEW.Quantity * (COALESCE(NEW.UnitCost, 0) - COALESCE(OLD.UnitCost, 0)), 2);
        IF v_Value <> 0 THEN
            v_Other := CASE WHEN COALESCE(OLD.UnitCost, 0) = 0 THEN '3100' ELSE '5300' END;
            PERFORM sp_PostJournal(CURRENT_DATE, 'Revaluation', 'revaluation', NEW.ItemID,
                format('Unit cost of %s changed from %s to %s', NEW.ItemName, COALESCE(OLD.UnitCost, 0), COALESCE(NEW.UnitCost, 0)),
                NULLIF(current_setting('app.user_id', TRUE), '')::INT,
                jsonb_build_array(jsonb_build_object('account', '1200', 'debit', v_Value),
                                  jsonb_build_object('account', v_Other, 'credit', v_Value)));
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'inventory_revalue') THEN
        CREATE TRIGGER inventory_revalue AFTER UPDATE OF UnitCost ON InventoryItems
            FOR EACH ROW EXECUTE FUNCTION trg_inventory_revalue();
    END IF;
END $$;

-- ------------------------------------------- Opening postings (once) ---
-- Existing stock value and existing cash-book rows, so the ledger starts in
-- agreement with what the system already records.
DO $$
DECLARE
    v_Value DECIMAL(16,2);
    r RECORD;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM JournalEntries WHERE SourceType = 'opening-stock') THEN
        SELECT COALESCE(SUM(Quantity * UnitCost), 0) INTO v_Value FROM InventoryItems WHERE Quantity > 0;
        IF v_Value > 0 THEN
            PERFORM sp_PostJournal(CURRENT_DATE, 'Opening stock', 'opening-stock', NULL, 'Stock value when the ledger started', NULL,
                jsonb_build_array(jsonb_build_object('account', '1200', 'debit', v_Value),
                                  jsonb_build_object('account', '3100', 'credit', v_Value)));
        END IF;
    END IF;

    FOR r IN SELECT * FROM FinanceTransactions WHERE EntryID IS NULL ORDER BY TransactionID LOOP
        UPDATE FinanceTransactions SET EntryID = (
            SELECT EntryID FROM sp_PostJournal(r.TxnDate, COALESCE(r.Description, initcap(r.Type)), 'finance', r.TransactionID,
                COALESCE(r.Category, initcap(r.Type)), NULL,
                CASE WHEN r.Type = 'income'
                     THEN jsonb_build_array(jsonb_build_object('account', '1010', 'debit', r.Amount),
                                            jsonb_build_object('account', '4100', 'credit', r.Amount))
                     ELSE jsonb_build_array(jsonb_build_object('account', '5200', 'debit', r.Amount),
                                            jsonb_build_object('account', '1010', 'credit', r.Amount)) END)),
            AccountCode = CASE WHEN r.Type = 'income' THEN '4100' ELSE '5200' END
        WHERE TransactionID = r.TransactionID;
    END LOOP;
END $$;

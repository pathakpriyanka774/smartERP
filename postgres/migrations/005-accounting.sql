-- ------------------------------------------------------------- Journal ---
CREATE TABLE IF NOT EXISTS JournalEntries (
    EntryID    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EntryDate  DATE NOT NULL,
    Reference  VARCHAR(100),
    SourceType VARCHAR(30),          -- invoice, payment, bill, stock, payroll, finance, manual, reversal
    SourceID   INT,
    Narration  VARCHAR(300),
    ReversalOf INT REFERENCES JournalEntries(EntryID),
    CreatedBy  INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt  TIMESTAMP DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_Journal_Date   ON JournalEntries (EntryDate);
CREATE INDEX IF NOT EXISTS IX_Journal_Source ON JournalEntries (SourceType, SourceID);

CREATE TABLE IF NOT EXISTS JournalLines (
    LineID    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EntryID   INT NOT NULL REFERENCES JournalEntries(EntryID),
    AccountID INT NOT NULL REFERENCES Accounts(AccountID),
    Debit     DECIMAL(16,2) NOT NULL DEFAULT 0 CHECK (Debit >= 0),
    Credit    DECIMAL(16,2) NOT NULL DEFAULT 0 CHECK (Credit >= 0),
    Memo      VARCHAR(200),
    CONSTRAINT CK_Journal_OneSide CHECK ((Debit > 0) <> (Credit > 0))
);
CREATE INDEX IF NOT EXISTS IX_JournalLines_Entry   ON JournalLines (EntryID);
CREATE INDEX IF NOT EXISTS IX_JournalLines_Account ON JournalLines (AccountID);

-- Debits must equal credits for every entry, checked when the transaction
-- commits (so lines can be inserted one at a time inside it).
CREATE OR REPLACE FUNCTION trg_journal_balanced() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_diff DECIMAL;
BEGIN
    SELECT COALESCE(SUM(Debit), 0) - COALESCE(SUM(Credit), 0) INTO v_diff
    FROM JournalLines WHERE EntryID = NEW.EntryID;
    IF v_diff <> 0 THEN
        RAISE EXCEPTION 'Journal entry % does not balance (difference %)', NEW.EntryID, v_diff;
    END IF;
    RETURN NULL;
END;
$$;

-- Posted accounting is never edited or deleted: corrections are reversals.
CREATE OR REPLACE FUNCTION trg_journal_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Posted journal entries cannot be changed or deleted; post a reversal instead';
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'journal_balanced') THEN
        CREATE CONSTRAINT TRIGGER journal_balanced AFTER INSERT ON JournalLines
            DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trg_journal_balanced();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'journal_lines_immutable') THEN
        CREATE TRIGGER journal_lines_immutable BEFORE UPDATE OR DELETE ON JournalLines
            FOR EACH ROW EXECUTE FUNCTION trg_journal_immutable();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'journal_entries_immutable') THEN
        CREATE TRIGGER journal_entries_immutable BEFORE UPDATE OR DELETE ON JournalEntries
            FOR EACH ROW EXECUTE FUNCTION trg_journal_immutable();
    END IF;
END $$;

/**
 * Post a balanced journal entry.
 *   p_Lines: [{ "account": "1100", "debit": 118.00, "memo": "..." }, { "account": "4000", "credit": 100.00 }, ...]
 * Amounts are rounded to paise; zero lines are skipped; a negative amount
 * moves to the other side. Raises if it does not balance or is empty.
 */
CREATE OR REPLACE FUNCTION sp_PostJournal(
    p_Date DATE, p_Reference VARCHAR, p_SourceType VARCHAR, p_SourceID INT,
    p_Narration VARCHAR, p_CreatedBy INT, p_Lines JSONB, p_ReversalOf INT DEFAULT NULL
)
RETURNS TABLE (EntryID INT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_ID   INT;
    v_Line JSONB;
    v_Acc  INT;
    v_Dr   DECIMAL(16,2);
    v_Cr   DECIMAL(16,2);
    v_TDr  DECIMAL(16,2) := 0;
    v_TCr  DECIMAL(16,2) := 0;
BEGIN
    INSERT INTO JournalEntries (EntryDate, Reference, SourceType, SourceID, Narration, CreatedBy, ReversalOf)
    VALUES (COALESCE(p_Date, CURRENT_DATE), p_Reference, p_SourceType, p_SourceID, p_Narration, p_CreatedBy, p_ReversalOf)
    RETURNING JournalEntries.EntryID INTO v_ID;

    FOR v_Line IN SELECT * FROM jsonb_array_elements(p_Lines) LOOP
        v_Dr := ROUND(COALESCE((v_Line->>'debit')::NUMERIC, 0), 2);
        v_Cr := ROUND(COALESCE((v_Line->>'credit')::NUMERIC, 0), 2);
        IF v_Dr < 0 THEN v_Cr := v_Cr - v_Dr; v_Dr := 0; END IF;
        IF v_Cr < 0 THEN v_Dr := v_Dr - v_Cr; v_Cr := 0; END IF;
        IF v_Dr > 0 AND v_Cr > 0 THEN
            IF v_Dr >= v_Cr THEN v_Dr := v_Dr - v_Cr; v_Cr := 0; ELSE v_Cr := v_Cr - v_Dr; v_Dr := 0; END IF;
        END IF;
        CONTINUE WHEN v_Dr = 0 AND v_Cr = 0;
        SELECT a.AccountID INTO v_Acc FROM Accounts a WHERE a.Code = v_Line->>'account';
        IF v_Acc IS NULL THEN
            RAISE EXCEPTION 'Unknown account %', v_Line->>'account';
        END IF;
        INSERT INTO JournalLines (EntryID, AccountID, Debit, Credit, Memo)
        VALUES (v_ID, v_Acc, v_Dr, v_Cr, LEFT(v_Line->>'memo', 200));
        v_TDr := v_TDr + v_Dr;
        v_TCr := v_TCr + v_Cr;
    END LOOP;

    IF v_TDr = 0 THEN
        RAISE EXCEPTION 'Journal entry has no amounts';
    END IF;
    IF v_TDr <> v_TCr THEN
        RAISE EXCEPTION 'Journal entry does not balance: debits %, credits %', v_TDr, v_TCr;
    END IF;
    RETURN QUERY SELECT v_ID;
END;
$$;

/** Reverse an entry: same accounts, debits and credits swapped. */
CREATE OR REPLACE FUNCTION sp_ReverseJournal(p_EntryID INT, p_Date DATE, p_CreatedBy INT, p_Narration VARCHAR DEFAULT NULL)
RETURNS TABLE (EntryID INT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Lines JSONB;
    v_Ref   VARCHAR(100);
BEGIN
    SELECT je.Reference INTO v_Ref FROM JournalEntries je WHERE je.EntryID = p_EntryID;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Journal entry % does not exist', p_EntryID;
    END IF;
    IF EXISTS (SELECT 1 FROM JournalEntries je WHERE je.ReversalOf = p_EntryID) THEN
        RAISE EXCEPTION 'Journal entry % has already been reversed', p_EntryID;
    END IF;
    SELECT jsonb_agg(jsonb_build_object('account', a.Code, 'debit', jl.Credit, 'credit', jl.Debit, 'memo', jl.Memo))
      INTO v_Lines
    FROM JournalLines jl JOIN Accounts a ON a.AccountID = jl.AccountID
    WHERE jl.EntryID = p_EntryID;
    RETURN QUERY SELECT * FROM sp_PostJournal(p_Date, 'Reversal of ' || COALESCE(v_Ref, '#' || p_EntryID), 'reversal', p_EntryID,
                                               COALESCE(p_Narration, 'Reversal'), p_CreatedBy, v_Lines, p_EntryID);
END;
$$;

-- Balance per account (debit-positive), for trial balance and dashboards.
CREATE OR REPLACE VIEW vw_AccountBalances AS
SELECT a.AccountID, a.Code, a.Name, a.Type,
       COALESCE(SUM(jl.Debit), 0)  AS TotalDebit,
       COALESCE(SUM(jl.Credit), 0) AS TotalCredit,
       COALESCE(SUM(jl.Debit), 0) - COALESCE(SUM(jl.Credit), 0) AS Balance
FROM Accounts a LEFT JOIN JournalLines jl ON jl.AccountID = a.AccountID
GROUP BY a.AccountID, a.Code, a.Name, a.Type;

-- ------------------------------------------------ Document numbering ---
-- Gapless numbers per document type and Indian financial year (April–March).
-- The counter row is locked until the creating transaction commits, so a
-- failed or rolled-back document never consumes a number.
CREATE TABLE IF NOT EXISTS DocumentSequences (
    DocType       VARCHAR(10) NOT NULL,
    FinancialYear VARCHAR(5)  NOT NULL,      -- '26-27'
    LastNumber    INT         NOT NULL,
    PRIMARY KEY (DocType, FinancialYear)
);

CREATE OR REPLACE FUNCTION fn_FinancialYear(p_Date DATE) RETURNS VARCHAR
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN EXTRACT(MONTH FROM p_Date) >= 4
                THEN to_char(p_Date, 'YY') || '-' || to_char(p_Date + INTERVAL '1 year', 'YY')
                ELSE to_char(p_Date - INTERVAL '1 year', 'YY') || '-' || to_char(p_Date, 'YY') END
$$;

CREATE OR REPLACE FUNCTION sp_NextDocNumber(p_DocType VARCHAR, p_Date DATE)
RETURNS TABLE (FinancialYear VARCHAR, Number INT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_FY VARCHAR(5) := fn_FinancialYear(p_Date);
    v_N  INT;
BEGIN
    INSERT INTO DocumentSequences (DocType, FinancialYear, LastNumber) VALUES (p_DocType, v_FY, 1)
    ON CONFLICT (DocType, FinancialYear) DO UPDATE SET LastNumber = DocumentSequences.LastNumber + 1
    RETURNING DocumentSequences.LastNumber INTO v_N;
    RETURN QUERY SELECT v_FY, v_N;
END;
$$;


-- --------------------------------------------- Stock posts to the ledger ---
/**
 * The one way stock changes (see migration 003), now also posting the value
 * of every movement, so the Inventory account always equals stock value:
 *   opening     Dr Inventory           Cr Opening Balance Equity
 *   receipt     Dr Inventory           Cr Goods Received Not Invoiced
 *   issue       Dr Materials Issued    Cr Inventory
 *   adjustment  Dr/Cr Inventory        against Inventory Adjustments
 *   consumption Dr Work in Progress    Cr Inventory
 *   production  Dr Inventory           Cr Work in Progress
 *   sale        Dr Cost of Goods Sold  Cr Inventory
 * Value = quantity × unit cost (the given cost for incoming stock, the
 * average cost for outgoing). Zero-value movements post nothing.
 */
CREATE OR REPLACE FUNCTION sp_StockMove(
    p_ItemID     INT,
    p_Type       VARCHAR,
    p_Quantity   INT,
    p_UnitCost   DECIMAL DEFAULT NULL,
    p_Reference  VARCHAR DEFAULT NULL,
    p_SourceType VARCHAR DEFAULT NULL,
    p_SourceID   INT     DEFAULT NULL,
    p_Notes      VARCHAR DEFAULT NULL,
    p_CreatedBy  INT     DEFAULT NULL,
    p_Date       DATE    DEFAULT NULL
)
RETURNS TABLE (MovementID INT, ItemID INT, BalanceAfter INT, UnitCost DECIMAL)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_Balance   INT;
    v_Cost      DECIMAL(12,2);
    v_OldCost   DECIMAL(12,2);
    v_Name      VARCHAR(150);
    v_OnHand    INT;
    v_Reserved  INT;
    v_MoveID    INT;
    v_Value     DECIMAL(16,2);
    v_Delta     DECIMAL(16,2);
    v_OldQty    INT;
    v_Dr        VARCHAR(10);
    v_Cr        VARCHAR(10);
BEGIN
    IF p_Quantity IS NULL OR p_Quantity = 0 THEN
        RAISE EXCEPTION 'Quantity must not be zero';
    END IF;

    SELECT i.UnitCost, i.Quantity INTO v_OldCost, v_OldQty FROM InventoryItems i WHERE i.ItemID = p_ItemID FOR UPDATE;

    UPDATE InventoryItems i
    SET Quantity = i.Quantity + p_Quantity,
        UnitCost = CASE
            WHEN p_Quantity > 0 AND p_UnitCost IS NOT NULL AND i.Quantity + p_Quantity > 0
            THEN ROUND((GREATEST(i.Quantity, 0) * i.UnitCost + p_Quantity * p_UnitCost)
                       / (GREATEST(i.Quantity, 0) + p_Quantity), 2)
            ELSE i.UnitCost END
    WHERE i.ItemID = p_ItemID
      AND i.Quantity + p_Quantity >= 0
      AND (p_Quantity > 0 OR i.Quantity + p_Quantity >= i.ReservedQuantity)
    RETURNING i.Quantity, i.UnitCost INTO v_Balance, v_Cost;

    IF NOT FOUND THEN
        SELECT i.ItemName, i.Quantity, i.ReservedQuantity INTO v_Name, v_OnHand, v_Reserved
        FROM InventoryItems i WHERE i.ItemID = p_ItemID;
        IF v_Name IS NULL THEN
            RAISE EXCEPTION 'Stock item % does not exist', p_ItemID;
        END IF;
        RAISE EXCEPTION 'Not enough stock of "%": % on hand, % reserved, % requested',
            v_Name, v_OnHand, v_Reserved, -p_Quantity;
    END IF;

    INSERT INTO StockMovements (ItemID, MovementType, Quantity, UnitCost, BalanceAfter,
                                Reference, SourceType, SourceID, Notes, CreatedBy)
    VALUES (p_ItemID, p_Type, p_Quantity,
            CASE WHEN p_Quantity > 0 THEN COALESCE(p_UnitCost, v_OldCost) ELSE v_OldCost END,
            v_Balance, p_Reference, p_SourceType, p_SourceID, p_Notes, p_CreatedBy)
    RETURNING StockMovements.MovementID INTO v_MoveID;

    v_Value := ROUND(ABS(p_Quantity) * CASE WHEN p_Quantity > 0 THEN COALESCE(p_UnitCost, v_OldCost) ELSE v_OldCost END, 2);
    v_Delta := ROUND(v_Balance * v_Cost - GREATEST(v_OldQty, 0) * v_OldCost, 2);
    IF v_Value > 0 THEN
        v_Dr := CASE p_Type
            WHEN 'opening' THEN '1200' WHEN 'receipt' THEN '1200' WHEN 'production' THEN '1200'
            WHEN 'issue' THEN '5310' WHEN 'consumption' THEN '1250' WHEN 'sale' THEN '5000'
            WHEN 'adjustment' THEN CASE WHEN p_Quantity > 0 THEN '1200' ELSE '5300' END END;
        v_Cr := CASE p_Type
            WHEN 'opening' THEN '3100' WHEN 'receipt' THEN '2050' WHEN 'production' THEN '1250'
            WHEN 'issue' THEN '1200' WHEN 'consumption' THEN '1200' WHEN 'sale' THEN '1200'
            WHEN 'adjustment' THEN CASE WHEN p_Quantity > 0 THEN '5300' ELSE '1200' END END;
        PERFORM sp_PostJournal(COALESCE(p_Date, CURRENT_DATE), COALESCE(p_Reference, initcap(p_Type)), 'stock', v_MoveID,
            format('%s %s × item %s', initcap(p_Type), ABS(p_Quantity), p_ItemID), p_CreatedBy,
            CASE WHEN p_Quantity > 0 THEN
                -- Incoming stock: Inventory moves by the exact change in stock
                -- value at the (rounded) average cost; the source account by
                -- quantity × price. Paise of rounding go to adjustments.
                jsonb_build_array(jsonb_build_object('account', v_Dr, 'debit', v_Delta),
                                  jsonb_build_object('account', v_Cr, 'credit', v_Value),
                                  jsonb_build_object('account', '5300', 'debit', v_Value - v_Delta, 'memo', 'Average-cost rounding'))
            ELSE
                jsonb_build_array(jsonb_build_object('account', v_Dr, 'debit', v_Value),
                                  jsonb_build_object('account', v_Cr, 'credit', v_Value))
            END);
    END IF;

    RETURN QUERY SELECT v_MoveID, p_ItemID, v_Balance, v_Cost;
END;
$$;

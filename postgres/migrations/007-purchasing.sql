-- Procure-to-pay: purchase orders with approval, goods receipts into stock,
-- supplier bills matched to what was received, and payments to suppliers.
--
--   PO (draft → submitted → approved → partially-received → received / closed)
--   Goods receipt: accepted quantity enters stock at the PO price
--                  (Dr Inventory, Cr Goods Received Not Invoiced)
--   Supplier bill: only for accepted, not-yet-billed quantity
--                  (Dr GRNI + Input GST, Cr Accounts Payable)
--   Payment out:   Dr Accounts Payable, Cr Bank / Cash

CREATE TABLE IF NOT EXISTS PurchaseOrders (
    POID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PONumber      VARCHAR(16) NOT NULL UNIQUE,
    SupplierID    INT NOT NULL REFERENCES Clients(ClientID),
    OrderDate     DATE NOT NULL,
    ExpectedDate  DATE,
    Status        VARCHAR(20) NOT NULL DEFAULT 'draft'
                  CHECK (Status IN ('draft', 'submitted', 'approved', 'partially-received', 'received', 'closed', 'cancelled')),
    Notes         VARCHAR(500),
    Subtotal      DECIMAL(16,2) NOT NULL DEFAULT 0,
    TaxAmount     DECIMAL(16,2) NOT NULL DEFAULT 0,
    Total         DECIMAL(16,2) NOT NULL DEFAULT 0,
    CreatedBy     INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt     TIMESTAMP DEFAULT LOCALTIMESTAMP,
    SubmittedAt   TIMESTAMP,
    ApprovedBy    INT REFERENCES Users(UserID) ON DELETE SET NULL,
    ApprovedAt    TIMESTAMP,
    ClosedAt      TIMESTAMP,
    CONSTRAINT CK_PO_Dates CHECK (ExpectedDate IS NULL OR ExpectedDate >= OrderDate),
    CONSTRAINT CK_PO_Amounts CHECK (Subtotal >= 0 AND TaxAmount >= 0 AND Total = Subtotal + TaxAmount)
);
CREATE INDEX IF NOT EXISTS IX_PO_Supplier ON PurchaseOrders (SupplierID);
CREATE INDEX IF NOT EXISTS IX_PO_Status   ON PurchaseOrders (Status);

CREATE TABLE IF NOT EXISTS PurchaseOrderItems (
    POItemID         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POID             INT NOT NULL REFERENCES PurchaseOrders(POID) ON DELETE CASCADE,
    ItemID           INT NOT NULL REFERENCES InventoryItems(ItemID),
    Description      VARCHAR(200) NOT NULL,
    Quantity         INT NOT NULL CHECK (Quantity > 0),
    UnitPrice        DECIMAL(12,2) NOT NULL CHECK (UnitPrice >= 0),
    GSTRate          DECIMAL(5,2) NOT NULL DEFAULT 0 CHECK (GSTRate BETWEEN 0 AND 40),
    LineTotal        DECIMAL(16,2) GENERATED ALWAYS AS (Quantity * UnitPrice) STORED,
    ReceivedQuantity INT NOT NULL DEFAULT 0,      -- accepted into stock
    -- Rejected goods go back to the supplier and do not count against the
    -- order, so a replacement delivery can still be received.
    RejectedQuantity INT NOT NULL DEFAULT 0,
    BilledQuantity   INT NOT NULL DEFAULT 0,
    CONSTRAINT CK_POItems_Progress CHECK (ReceivedQuantity BETWEEN 0 AND Quantity AND RejectedQuantity >= 0
        AND BilledQuantity BETWEEN 0 AND ReceivedQuantity)
);
CREATE INDEX IF NOT EXISTS IX_POItems_PO   ON PurchaseOrderItems (POID);
CREATE INDEX IF NOT EXISTS IX_POItems_Item ON PurchaseOrderItems (ItemID);

CREATE TABLE IF NOT EXISTS GoodsReceipts (
    GRNID       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GRNNumber   VARCHAR(16) NOT NULL UNIQUE,
    POID        INT NOT NULL REFERENCES PurchaseOrders(POID),
    ReceiptDate DATE NOT NULL,
    SupplierRef VARCHAR(60),          -- delivery challan number
    Notes       VARCHAR(300),
    CreatedBy   INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt   TIMESTAMP DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_GRN_PO ON GoodsReceipts (POID);

CREATE TABLE IF NOT EXISTS GoodsReceiptItems (
    GRNItemID        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GRNID            INT NOT NULL REFERENCES GoodsReceipts(GRNID) ON DELETE CASCADE,
    POItemID         INT NOT NULL REFERENCES PurchaseOrderItems(POItemID),
    AcceptedQuantity INT NOT NULL DEFAULT 0 CHECK (AcceptedQuantity >= 0),
    RejectedQuantity INT NOT NULL DEFAULT 0 CHECK (RejectedQuantity >= 0),
    RejectReason     VARCHAR(200),
    MovementID       INT REFERENCES StockMovements(MovementID),
    CONSTRAINT CK_GRNItems_Some CHECK (AcceptedQuantity + RejectedQuantity > 0)
);
CREATE INDEX IF NOT EXISTS IX_GRNItems_GRN ON GoodsReceiptItems (GRNID);

CREATE TABLE IF NOT EXISTS SupplierBills (
    BillID        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BillRef       VARCHAR(16) NOT NULL UNIQUE,    -- our number, BILL/26-27/00001
    SupplierBillNo VARCHAR(30) NOT NULL,          -- the supplier's invoice number
    SupplierID    INT NOT NULL REFERENCES Clients(ClientID),
    POID          INT REFERENCES PurchaseOrders(POID),
    BillDate      DATE NOT NULL,
    DueDate       DATE NOT NULL,
    SupplyType    VARCHAR(5) NOT NULL CHECK (SupplyType IN ('intra', 'inter')),
    TaxableValue  DECIMAL(16,2) NOT NULL,
    CGST          DECIMAL(16,2) NOT NULL DEFAULT 0,
    SGST          DECIMAL(16,2) NOT NULL DEFAULT 0,
    IGST          DECIMAL(16,2) NOT NULL DEFAULT 0,
    RoundOff      DECIMAL(6,2)  NOT NULL DEFAULT 0,
    Total         DECIMAL(16,2) NOT NULL,
    AmountPaid    DECIMAL(16,2) NOT NULL DEFAULT 0,
    Status        VARCHAR(15) NOT NULL DEFAULT 'open' CHECK (Status IN ('open', 'partially-paid', 'paid', 'cancelled')),
    Notes         VARCHAR(300),
    EntryID       INT REFERENCES JournalEntries(EntryID),
    CancelEntryID INT REFERENCES JournalEntries(EntryID),
    CancelledAt   TIMESTAMP,
    CancelledBy   INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedBy     INT REFERENCES Users(UserID) ON DELETE SET NULL,
    CreatedAt     TIMESTAMP DEFAULT LOCALTIMESTAMP,
    -- The same supplier invoice cannot be booked twice.
    CONSTRAINT UQ_Bills_SupplierNo UNIQUE (SupplierID, SupplierBillNo),
    CONSTRAINT CK_Bills_Totals CHECK (Total = TaxableValue + CGST + SGST + IGST + RoundOff AND ABS(RoundOff) < 1
        AND (SupplyType = 'intra' OR (CGST = 0 AND SGST = 0)) AND (SupplyType = 'inter' OR IGST = 0)),
    CONSTRAINT CK_Bills_Paid CHECK (AmountPaid >= 0 AND AmountPaid <= Total),
    CONSTRAINT CK_Bills_Due CHECK (DueDate >= BillDate)
);
CREATE INDEX IF NOT EXISTS IX_Bills_Supplier ON SupplierBills (SupplierID);
CREATE INDEX IF NOT EXISTS IX_Bills_PO       ON SupplierBills (POID);

CREATE TABLE IF NOT EXISTS SupplierBillItems (
    BillItemID   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BillID       INT NOT NULL REFERENCES SupplierBills(BillID) ON DELETE CASCADE,
    POItemID     INT REFERENCES PurchaseOrderItems(POItemID),
    Description  VARCHAR(200) NOT NULL,
    Quantity     INT NOT NULL CHECK (Quantity > 0),
    UnitPrice    DECIMAL(12,2) NOT NULL CHECK (UnitPrice >= 0),
    TaxableValue DECIMAL(16,2) NOT NULL,
    GSTRate      DECIMAL(5,2)  NOT NULL CHECK (GSTRate BETWEEN 0 AND 40),
    CGST         DECIMAL(16,2) NOT NULL DEFAULT 0,
    SGST         DECIMAL(16,2) NOT NULL DEFAULT 0,
    IGST         DECIMAL(16,2) NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS IX_BillItems_Bill ON SupplierBillItems (BillID);

